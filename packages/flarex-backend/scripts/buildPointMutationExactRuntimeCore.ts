import { buildRuntimeKernelTwice } from "./runtimeKernelBuilder";
import { writeFile } from "node:fs/promises";
import * as path from "node:path";
import { fileURLToPath, pathToFileURL } from "node:url";

const PACKAGE_ROOT = fileURLToPath(new URL("..", import.meta.url));
const CORE_PATH = path.join(
  PACKAGE_ROOT,
  "src",
  "artifactRuntime",
  "PointMutationExactRuntimeWorkerCore.ts",
);
const GENERATED_PATH = path.join(
  PACKAGE_ROOT,
  "src",
  "artifactRuntime",
  "PointMutationExactRuntimeWorkerCore.generated.ts",
);
interface CoreBuildReceipt {
  readonly source: string;
  readonly sha256: string;
}

if (
  process.argv[1] !== undefined &&
  import.meta.url === pathToFileURL(path.resolve(process.argv[1])).href
) {
  const mode = process.argv[2];
  if (mode !== "update" && mode !== "check") {
    throw new Error(
      "Usage: buildPointMutationExactRuntimeCore.ts <update|check>",
    );
  }
  const receipt = mode === "update"
    ? await updatePointMutationExactRuntimeCore()
    : await checkPointMutationExactRuntimeCore();
  console.log(
    `Verified exact point-mutation runtime core ${receipt.sha256} ` +
      "with two byte-identical clean builds.",
  );
}

export async function updatePointMutationExactRuntimeCore(): Promise<
  CoreBuildReceipt
> {
  const receipt = await buildTwice();
  await writeFile(GENERATED_PATH, renderGeneratedModule(receipt), "utf8");
  return receipt;
}

export async function checkPointMutationExactRuntimeCore(): Promise<
  CoreBuildReceipt
> {
  const expected = await buildTwice();
  const generatedUrl = `${pathToFileURL(GENERATED_PATH).href}?check=${Date.now()}`;
  const generated: unknown = await import(generatedUrl);
  if (!isGeneratedCoreModule(generated)) {
    throw new Error("Generated exact-runtime core module has an invalid shape.");
  }
  if (
    generated.POINT_MUTATION_EXACT_RUNTIME_WORKER_CORE_SOURCE_V1 !==
      expected.source ||
    generated.POINT_MUTATION_EXACT_RUNTIME_WORKER_CORE_SHA256_V1 !==
      expected.sha256
  ) {
    throw new Error(
      "Generated exact point-mutation runtime core is stale; run " +
        "`pnpm exact-runtime-core:update` in packages/flarex-backend.",
    );
  }
  return expected;
}

async function buildTwice(): Promise<CoreBuildReceipt> {
  const { source, sha256 } = await buildRuntimeKernelTwice({
    entry: CORE_PATH,
    label: "Exact point-mutation runtime core",
    minify: false,
    externalModules: [
      "cloudflare:workers",
      "flarex:function-api-core/v1",
      "./_flarex/application-error-platform-v1.js",
      "./pointMutationExactRuntimeWorker/flarex-point-mutation-exact-runtime-config-v1.js",
      "./pointMutationExactRuntimeWorker/flarex-point-mutation-exact-runtime-execution-v1.js",
      "./pointMutationExactRuntimeWorker/flarex-point-mutation-runtime-kernel-v1.js",
    ],
  });
  return Object.freeze({ source, sha256 });
}

function isGeneratedCoreModule(value: unknown): value is Readonly<{
  readonly POINT_MUTATION_EXACT_RUNTIME_WORKER_CORE_SOURCE_V1: string;
  readonly POINT_MUTATION_EXACT_RUNTIME_WORKER_CORE_SHA256_V1: string;
}> {
  return (
    typeof value === "object" &&
    value !== null &&
    "POINT_MUTATION_EXACT_RUNTIME_WORKER_CORE_SOURCE_V1" in value &&
    typeof value.POINT_MUTATION_EXACT_RUNTIME_WORKER_CORE_SOURCE_V1 ===
      "string" &&
    "POINT_MUTATION_EXACT_RUNTIME_WORKER_CORE_SHA256_V1" in value &&
    typeof value.POINT_MUTATION_EXACT_RUNTIME_WORKER_CORE_SHA256_V1 ===
      "string"
  );
}

function renderGeneratedModule(receipt: CoreBuildReceipt): string {
  const sourceLines = receipt.source.match(/[^\n]*\n|[^\n]+$/g) ?? [];
  const renderedLines = sourceLines.map((line) => `  ${JSON.stringify(line)},`);
  return [
    "// Generated by scripts/buildPointMutationExactRuntimeCore.ts. Do not edit by hand.",
    "export const POINT_MUTATION_EXACT_RUNTIME_WORKER_CORE_SOURCE_V1 = [",
    ...renderedLines,
    '].join("");',
    "",
    "export const POINT_MUTATION_EXACT_RUNTIME_WORKER_CORE_SHA256_V1 =",
    `  ${JSON.stringify(receipt.sha256)};`,
    "",
  ].join("\n");
}
