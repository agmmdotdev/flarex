import * as path from "node:path";
import { fileURLToPath, pathToFileURL } from "node:url";

import { buildRuntimeKernelTwice, writeOrCheckGeneratedFile } from "./runtimeKernelBuilder";

const PACKAGE_ROOT = fileURLToPath(new URL("..", import.meta.url));
const CORE = path.join(
  PACKAGE_ROOT, "src", "artifactRuntime", "PointMutationInternalCallExactRuntimeWorkerCore.ts",
);
const GENERATED = path.join(
  PACKAGE_ROOT, "src", "artifactRuntime", "PointMutationInternalCallExactRuntimeWorkerCore.generated.ts",
);

if (process.argv[1] !== undefined &&
  import.meta.url === pathToFileURL(path.resolve(process.argv[1])).href) {
  const mode = process.argv[2];
  if (mode !== "update" && mode !== "check") {
    throw new Error("Usage: buildPointMutationInternalCallExactRuntimeCore.ts <update|check>");
  }
  const receipt = await buildTwice();
  await writeOrCheckGeneratedFile(
    GENERATED,
    render(receipt),
    mode,
    "Generated exact point-mutation internal-call runtime core is stale; run point-mutation-internal-call-exact-runtime-core:update.",
  );
  console.log(`Verified exact point-mutation internal-call runtime core ${receipt.sha256}.`);
}

async function buildTwice() {
  const { source, sha256 } = await buildRuntimeKernelTwice({
    entry: CORE,
    label: "Point-mutation internal-call exact runtime core",
    minify: false,
    externalModules: [
      "cloudflare:workers",
      "flarex:function-api-core/v1",
      "./_flarex/application-error-platform-v1.js",
      "./pointMutationInternalCallExactRuntimeWorker/flarex-point-mutation-internal-call-exact-runtime-config-v1.js",
      "./pointMutationInternalCallExactRuntimeWorker/flarex-point-mutation-internal-call-exact-runtime-execution-v1.js",
      "./pointMutationInternalCallExactRuntimeWorker/flarex-point-mutation-internal-call-runtime-kernel-v1.js",
    ],
  });
  return Object.freeze({ source, sha256 });
}

function render(receipt: Readonly<{ readonly source: string; readonly sha256: string }>) {
  const lines = receipt.source.match(/[^\n]*\n|[^\n]+$/g) ?? [];
  return [
    "// Generated by scripts/buildPointMutationInternalCallExactRuntimeCore.ts. Do not edit by hand.",
    "export const POINT_MUTATION_INTERNAL_CALL_EXACT_RUNTIME_WORKER_CORE_SOURCE_V1 = [",
    ...lines.map(line => `  ${JSON.stringify(line)},`),
    '].join("");',
    "",
    "export const POINT_MUTATION_INTERNAL_CALL_EXACT_RUNTIME_WORKER_CORE_SHA256_V1 =",
    `  ${JSON.stringify(receipt.sha256)};`,
    "",
  ].join("\n");
}
