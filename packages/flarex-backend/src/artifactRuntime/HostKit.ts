import {
  generatedExecutionWorkerSource,
  type GeneratedExecutionWorkerSourceOptions,
} from "./GeneratedWorkerSource.ts";

export type ExecutionArtifactRuntimeWorkerSourceProfile =
  | "local-miniflare"
  | "hosted-dynamic-worker";

export type ExecutionArtifactRuntimeWorkerSourceOptions = {
  readonly profile: ExecutionArtifactRuntimeWorkerSourceProfile;
  readonly executionModule: string;
};

type ExecutionArtifactRuntimeWorkerSourceProfileOptions = Omit<
  GeneratedExecutionWorkerSourceOptions,
  "executionModule" | "includeQuerySessionRoute" | "includeUnsupportedCapabilities"
> & {
  readonly includeQuerySessionRoute?: true;
  readonly includeUnsupportedCapabilities?: true;
};

const RUNTIME_WORKER_SOURCE_PROFILES = {
  "local-miniflare": {
    headerComment: "// Generated by flarex-dev for local execution-artifact runtime materialization.",
    backendBinding: "FLAREX_BACKEND",
    backendBaseUrl: "https://flarex-backend.internal",
    missingBackendBindingMessage: "FLAREX_BACKEND service binding is required for local execution artifact runtime.",
    includeQuerySessionRoute: true,
  },
  "hosted-dynamic-worker": {
    headerComment: "// Generated by Flarex artifact-runtime for Dynamic Worker execution.",
    backendBinding: "FLAREX_EXECUTOR",
    backendBaseUrl: "https://flarex-executor.internal",
    missingBackendBindingMessage: "FLAREX_EXECUTOR service binding is required for hosted Dynamic Worker execution.",
    includeUnsupportedCapabilities: true,
  },
} satisfies Record<
  ExecutionArtifactRuntimeWorkerSourceProfile,
  ExecutionArtifactRuntimeWorkerSourceProfileOptions
>;

export function executionArtifactRuntimeWorkerSource(
  options: ExecutionArtifactRuntimeWorkerSourceOptions,
): string {
  const profile = RUNTIME_WORKER_SOURCE_PROFILES[options.profile];
  return generatedExecutionWorkerSource({
    ...profile,
    executionModule: options.executionModule,
  });
}
