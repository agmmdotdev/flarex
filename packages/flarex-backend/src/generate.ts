import { mkdir, readFile, readdir, writeFile } from "node:fs/promises";
import path from "node:path";

export type FlarexGenerateOptions = {
  root: string;
  appDir?: string;
  generatedDir?: string;
  workerName?: string;
};

type DiscoveredFunction = {
  moduleName: string;
  exportName: string;
  kind: string;
};

async function discoverFunctions(functionsDir: string): Promise<DiscoveredFunction[]> {
  const entries = await readdir(functionsDir, { recursive: true, withFileTypes: true }).catch(error => {
    if ((error as NodeJS.ErrnoException).code === "ENOENT") return [];
    throw error;
  });
  const functions: DiscoveredFunction[] = [];

  for (const entry of entries) {
    if (!entry.isFile() || !entry.name.endsWith(".ts")) continue;
    const absolute = path.join(entry.parentPath, entry.name);
    const source = await readFile(absolute, "utf8");
    const relative = path.relative(functionsDir, absolute).replaceAll("\\", "/").replace(/\.ts$/, "");
    const expression =
      /export\s+const\s+(\w+)\s*=\s*(query|mutation|workflowMutation|action)\s*\(/g;
    for (const match of source.matchAll(expression)) {
      functions.push({ moduleName: relative, exportName: match[1]!, kind: match[2]! });
    }
  }

  return functions.sort((a, b) =>
    `${a.moduleName}:${a.exportName}`.localeCompare(`${b.moduleName}:${b.exportName}`),
  );
}

function typedApi(functions: DiscoveredFunction[]): string {
  const modules = [...new Set(functions.map(fn => fn.moduleName))];
  const imports = modules
    .map(
      (moduleName, index) =>
        `import type * as module${index} from "../functions/${moduleName}";`,
    )
    .join("\n");
  const moduleTypes = modules
    .map((moduleName, index) => `  ${JSON.stringify(moduleName)}: typeof module${index};`)
    .join("\n");

  return `// Generated by flarex-backend. Do not edit.
import { anyApi, type ApiFromModules } from "flarex/server";
${imports}

export const api = anyApi as unknown as ApiFromModules<{
${moduleTypes}
}>;
`;
}

function dataModelSource(): string {
  return `// Generated by flarex-backend. Do not edit.
import type {
  DataModelFromSchemaDefinition,
  DocumentByName,
  TableNamesInDataModel,
} from "flarex/server";
import schema from "../schema";

export type DataModel = DataModelFromSchemaDefinition<typeof schema>;
export type Doc<TableName extends TableNamesInDataModel<DataModel>> =
  DocumentByName<DataModel, TableName>;
export type TableNames = TableNamesInDataModel<DataModel>;
`;
}

