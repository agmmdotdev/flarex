function functionMetadataSource(modules: AnalyzedModule[]): string {
  const metadata = modules.flatMap(module =>
    module.functions.map(fn => ({
      path: functionPath(fn),
      kind: fn.kind,
      visibility: fn.visibility,
      args: fn.args,
      returns: fn.returns,
      route: fn.route ?? null,
      partition: fn.partition ?? null,
      ...(fn.position === undefined ? {} : { position: fn.position }),
    })),
  );
  return `// Generated by flarex-dev. Do not edit.
import type { ValidatorJSON } from "flarex/values";

export type FunctionMetadata = {
  path: string;
  kind: "query" | "mutation" | "workflowMutation" | "action";
  visibility: "public" | "internal";
  args: ValidatorJSON;
  returns: ValidatorJSON | null;
  route: { type: "args"; field: string } | null;
  partition: {
    type: "partition";
    table: string;
    selector: string;
    partitionField: string;
    argField: string;
  } | null;
  position?: {
    path: string;
    startLine: number;
    startColumn: number;
  };
};

export const functionMetadata: FunctionMetadata[] = ${JSON.stringify(metadata, null, 2)};

export default functionMetadata;
`;
}

function dynamicPartitionModelSource(): string {
  return `const partitionFieldForSelector = (selector: string) => {
  if (selector === "byId") return "_id";
  if (!selector.startsWith("by") || selector.length <= 2) return "partition";
  const suffix = selector.slice(2);
  return \`\${suffix[0].toLowerCase()}\${suffix.slice(1)}\`;
};

const dynamicPartitionTable = (table: string) => new Proxy({}, {
  get(_target, property) {
    if (typeof property !== "string") return undefined;
    return (argField: string) => ({
      type: "partition",
      table,
      selector: property,
      partitionField: partitionFieldForSelector(property),
      argField,
    } as const);
  },
}) as Record<string, (argField: string) => {
  type: "partition";
  table: string;
  selector: string;
  partitionField: string;
  argField: string;
}>;

export const model = new Proxy({}, {
  get(_target, property) {
    if (typeof property !== "string") return undefined;
    return dynamicPartitionTable(property);
  },
}) as Record<string, ReturnType<typeof dynamicPartitionTable>>;`;
}

function concretePartitionModelSource(schema: AnalyzedSchema): string {
  const entries = schema.tables
    .flatMap(table => {
      if (table.placement.kind !== "partitionBy") return [];
      const selector = selectorNameForPartitionField(table.placement.field);
      return [`  ${propertyKey(table.name)}: {
    ${propertyKey(selector)}: (argField: string) => ({
      type: "partition",
      table: ${JSON.stringify(table.name)},
      selector: ${JSON.stringify(selector)},
      partitionField: ${JSON.stringify(table.placement.field)},
      argField,
    } as const),
  },`];
    });
  return `export const model = {
${entries.join("\n")}
} as const;`;
}

function selectorNameForPartitionField(field: string): string {
  if (field === "_id") return "byId";
  const suffix = field
    .split(/[^A-Za-z0-9]+/)
    .filter(part => part.length > 0)
    .map(capitalize)
    .join("");
  return suffix.length === 0 ? "byPartition" : `by${suffix}`;
}

function capitalize(value: string): string {
  return value.length === 0 ? value : `${value[0]!.toUpperCase()}${value.slice(1)}`;
}

function propertyKey(value: string): string {
  return /^[A-Za-z_$][A-Za-z0-9_$]*$/.test(value) ? value : JSON.stringify(value);
}

function functionRegistrySource(modules: AnalyzedModule[]): string {
  const activeModules = modules.filter(module => module.functions.length > 0);
  const imports = activeModules
    .map(
      (module, index) => `import * as module${index} from "../functions/${module.moduleName}";`,
    )
    .join("\n");
  const registry = activeModules
    .flatMap((module, moduleIndex) =>
      module.functions.map(
        fn =>
          `  ${JSON.stringify(functionPath(fn))}: module${moduleIndex}.${fn.exportName},`,
      ),
    )
    .join("\n");
  return `// Generated by flarex-dev. Do not edit.
import type { RegisteredFunction } from "flarex/server";
${imports}

export const functions: Record<string, RegisteredFunction> = {
${registry}
};
`;
}

