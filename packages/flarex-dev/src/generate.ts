function workerSource(): string {
  return `// Generated by flarex-dev. Do not edit.
import { DurableObject } from "cloudflare:workers";
import {
  createQueryInitializer,
  parseFlarexId,
  validateValue,
  type DatabaseQueryRequest,
  type DatabaseQueryResult,
  type DatabaseWriter,
} from "flarex/server";
import { deploymentSchema } from "./deploymentSchema";
import { functionMetadata } from "./functionMetadata";
import { functions } from "./functionRegistry";

const functionMetadataByPath = new Map(
  functionMetadata.map(metadata => [metadata.path, metadata] as const),
);

const tableMetadata = Object.fromEntries(
  deploymentSchema.tables
    .filter(table => table.state !== "deleted")
    .map(table => [table.name, { tableId: table.tableId, name: table.name }]),
) as Record<string, { tableId: number; name: string }>;

const tableNamesById = new Map(
  Object.values(tableMetadata).map(table => [table.tableId, table.name] as const),
);

export interface Env {
  CONNECTIONS: DurableObjectNamespace<ConnectionDO>;
  FLAREX_BACKEND: Fetcher;
  FLAREX_DEPLOYMENT_ID?: string;
  FLAREX_INTERNAL_TOKEN?: string;
}

export class ConnectionDO extends DurableObject<Env> {
  async fetch(request: Request): Promise<Response> {
    if (request.headers.get("Upgrade") !== "websocket") {
      return Response.json({ service: "flarex-connection", status: "ok" });
    }
    const pair = new WebSocketPair();
    const [client, server] = Object.values(pair) as [WebSocket, WebSocket];
    this.ctx.acceptWebSocket(server);
    server.send(JSON.stringify({ type: "Connected", protocol: "flarex-v0" }));
    return new Response(null, { status: 101, webSocket: client });
  }
}

function validateFunctionReturn(
  validator: (typeof functionMetadata)[number]["returns"],
  value: unknown,
): void {
  if (validator === null) return;
  validateValue(validator, value, "$return", { validateId: validateTableNameId });
}

function validateTableNameId(tableName: string, value: string, path: string): void {
  const expected = tableMetadata[tableName];
  if (!expected) {
    throw new Error(\`\${path}: Unknown table \${tableName} for ID validator.\`);
  }
  const parsed = parseFlarexId(value);
  if (parsed === null) {
    throw new Error(\`\${path}: Expected an ID for table \${tableName}.\`);
  }
  if (parsed.tableId !== expected.tableId) {
    const actualTableName = tableNamesById.get(parsed.tableId);
    const suffix = actualTableName === undefined ? "" : \`, got an ID for table \${actualTableName}\`;
    throw new Error(\`\${path}: Expected an ID for table \${tableName}\${suffix}.\`);
  }
}

type InvokeBody = {
  path: string;
  args: unknown;
  partitionKey?: string;
  deploymentId?: string;
  idempotencyKey?: string;
};

type ExecutionStartResponse = {
  sessionId: string;
  kind: "query" | "mutation";
};

async function invokeWithBackend(body: InvokeBody, env: Env, request: Request): Promise<unknown> {
  const fn = functions[body.path];
  if (!fn) throw new Error(\`Unknown Flarex function: \${body.path}\`);
  const metadata = functionMetadataByPath.get(body.path);
  if (!metadata) throw new Error(\`Missing analyzed metadata for Flarex function: \${body.path}\`);
  if (metadata.kind !== "query" && metadata.kind !== "mutation") {
    throw new Error(\`\${metadata.kind} execution is not implemented by /invoke\`);
  }
  validateValue(metadata.args, body.args, "$args", { validateId: validateTableNameId });

  const deploymentId =
    request.headers.get("x-flarex-deployment") ?? body.deploymentId ?? env.FLAREX_DEPLOYMENT_ID;
  if (!deploymentId) throw new Error("A deploymentId or x-flarex-deployment header is required.");
  const partitionKey = request.headers.get("x-flarex-partition") ?? body.partitionKey;
  if (!partitionKey) throw new Error("A partitionKey or x-flarex-partition header is required.");

  const start = await postBackend<ExecutionStartResponse>(
    env.FLAREX_BACKEND,
    \`/deployments/\${deploymentId}/executions/start\`,
    {
      path: body.path,
      args: body.args,
      kind: metadata.kind,
      partitionKey,
      ...(body.idempotencyKey === undefined ? {} : { idempotencyKey: body.idempotencyKey }),
    },
  );
  try {
    const db = databaseForSession(env.FLAREX_BACKEND, deploymentId, start.sessionId, start.kind);
    const value = await fn._handler({ db } as never, body.args as never);
    validateFunctionReturn(metadata.returns, value);
    return await postBackend(env.FLAREX_BACKEND, \`/deployments/\${deploymentId}/executions/\${start.sessionId}/finish\`, {
      value,
    });
  } catch (error) {
    await postBackend(env.FLAREX_BACKEND, \`/deployments/\${deploymentId}/executions/\${start.sessionId}/abort\`, {}).catch(
      () => undefined,
    );
    throw error;
  }
}

function databaseForSession(
  backend: Fetcher,
  deploymentId: string,
  sessionId: string,
  kind: "query" | "mutation",
): DatabaseWriter {
  const syscall = (body: unknown) =>
    postBackend<unknown>(backend, \`/deployments/\${deploymentId}/executions/\${sessionId}/syscall\`, body);
  const query = (request: DatabaseQueryRequest) =>
    syscall({ op: "query", request }) as Promise<DatabaseQueryResult>;
  return {
    get: id => syscall({ op: "get", id }) as never,
    query: table => createQueryInitializer(table, query),
    insert: async (table, value) => {
      if (kind !== "mutation") throw new Error("Cannot insert during a query.");
      return (await syscall({ op: "insert", table, value })) as never;
    },
    patch: async (id, value) => {
      if (kind !== "mutation") throw new Error("Cannot patch during a query.");
      await syscall({ op: "patch", id, value });
    },
    delete: async id => {
      if (kind !== "mutation") throw new Error("Cannot delete during a query.");
      await syscall({ op: "delete", id });
    },
  };
}

async function postBackend<T>(backend: Fetcher, path: string, body: unknown): Promise<T> {
  const response = await backend.fetch(\`https://flarex-backend.internal\${path}\`, {
    method: "POST",
    headers: { "content-type": "application/json" },
    body: JSON.stringify(body),
  });
  const value = await response.json().catch(() => null);
  if (!response.ok) {
    const message =
      typeof value === "object" && value !== null && "error" in value
        ? String((value as { error: unknown }).error)
        : \`Backend request failed with status \${response.status}\`;
    throw new Error(message);
  }
  return value as T;
}

function authorizeInternalRequest(request: Request, env: Env): Response | null {
  if (env.FLAREX_INTERNAL_TOKEN === undefined) return null;
  const expected = \`Bearer \${env.FLAREX_INTERNAL_TOKEN}\`;
  if (request.headers.get("authorization") === expected) return null;
  return Response.json({ error: "Unauthorized internal Flarex request." }, { status: 401 });
}

export default {
  async fetch(request: Request, env: Env): Promise<Response> {
    const url = new URL(request.url);
    if (url.pathname.startsWith("/__flarex_internal/")) {
      const unauthorized = authorizeInternalRequest(request, env);
      if (unauthorized !== null) return unauthorized;
    }
    if (url.pathname === "/sync") {
      const session = request.headers.get("x-flarex-session") ?? crypto.randomUUID();
      return env.CONNECTIONS.getByName(session).fetch(request);
    }
    if (
      (url.pathname === "/invoke" || url.pathname === "/__flarex_internal/invoke") &&
      request.method === "POST"
    ) {
      try {
        return Response.json(await invokeWithBackend(await request.json<InvokeBody>(), env, request));
      } catch (error) {
        return Response.json(
          { error: error instanceof Error ? error.message : String(error) },
          { status: 400 },
        );
      }
    }
    if (url.pathname === "/health") {
      return Response.json({ service: "flarex", status: "ok" });
    }
    if (url.pathname === "/__flarex_internal/metadata") {
      return Response.json({ schema: deploymentSchema, functions: functionMetadata });
    }
    return Response.json({ error: "Not implemented." }, { status: 501 });
  },
} satisfies ExportedHandler<Env>;
`;
}

export async function generateFlarex(options: FlarexGenerateOptions): Promise<void> {
  const context = await initialCodegen(options);
  const sourcePackage = await bundleFlarexSourcePackage(context);
  const analysis = await new LocalMiniflareExecutionArtifactAdapter().analyze(sourcePackage);
  await finalCodegen(context, analysis);
}

export async function initialCodegen(
  options: FlarexGenerateOptions,
): Promise<FlarexGenerationContext> {
  const appDir = path.resolve(options.root, options.appDir ?? "flarex");
  const generatedDir = path.resolve(appDir, options.generatedDir ?? "_generated");
  const functionsDir = path.join(appDir, "functions");
  const functionModules = await listFunctionModules(functionsDir);
  const moduleNames = functionModules.map(module => module.moduleName);
  await mkdir(generatedDir, { recursive: true });

  await writeFile(path.join(generatedDir, "dataModel.ts"), dataModelSource());
  await writeFile(path.join(generatedDir, "server.ts"), serverSource());
  await writeFile(path.join(generatedDir, "api.ts"), typedApi(moduleNames));
  return { options, appDir, generatedDir, functionsDir, functionModules };
}

export function bundleFlarexSourcePackage(
  context: FlarexGenerationContext,
): Promise<SourcePackage> {
  return bundleSourcePackage({
    appDir: context.appDir,
    functionModules: context.functionModules,
  });
}

export async function finalCodegen(
  context: FlarexGenerationContext,
  analysis: DeploymentAnalysis,
): Promise<void> {
  const { generatedDir } = context;
  const functions = analysis.functions;
  await writeFile(path.join(generatedDir, "dataModel.ts"), dataModelSource());
  await writeFile(path.join(generatedDir, "server.ts"), serverSource(analysis.schema));
  await writeFile(
    path.join(generatedDir, "api.ts"),
    typedApi(functions.map(module => module.moduleName), referenceMetadataMapSource(functions)),
  );
  await writeFile(path.join(generatedDir, "functionRegistry.ts"), functionRegistrySource(functions));
  await writeFile(path.join(generatedDir, "functionMetadata.ts"), functionMetadataSource(functions));
  await writeFile(path.join(generatedDir, "deploymentSchema.ts"), deploymentSchemaSource(analysis.schema));
  await writeFile(path.join(generatedDir, "worker.ts"), workerSource());
  await cleanupStaleGeneratedEntries(generatedDir, [
    "api.ts",
    "dataModel.ts",
    "deploymentSchema.ts",
    "functionMetadata.ts",
    "functionRegistry.ts",
    "server.ts",
    "worker.ts",
  ]);
}

function functionPath(fn: AnalyzedFunction): string {
  return fn.exportName === "default" ? fn.moduleName : `${fn.moduleName}:${fn.exportName}`;
}

function referenceMetadataMapSource(modules: AnalyzedModule[]): Record<string, unknown> {
  return Object.fromEntries(
    modules.flatMap(module =>
      module.functions.flatMap(fn => {
        if (
          (fn.route === null || fn.route === undefined) &&
          (fn.partition === null || fn.partition === undefined)
        ) {
          return [];
        }
        return [[
          functionPath(fn),
          {
            route: fn.route ?? null,
            partition: fn.partition ?? null,
          },
        ]];
      }),
    ),
  );
}

async function cleanupStaleGeneratedEntries(
  generatedDir: string,
  writtenFiles: string[],
): Promise<void> {
  const entries = await readdir(generatedDir, { withFileTypes: true });
  await Promise.all(
    entries
      .filter(entry => !writtenFiles.includes(entry.name))
      .map(entry => rm(path.join(generatedDir, entry.name), { recursive: true, force: true })),
  );
}
