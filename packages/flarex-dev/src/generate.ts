function typedApi(modules: string[], metadataByPath: Record<string, unknown> = {}): string {
  const imports = modules
    .map(
      (moduleName, index) =>
        `import type * as module${index} from "../functions/${moduleName}";`,
    )
    .join("\n");
  const moduleTypes = modules
    .map((moduleName, index) => `  ${JSON.stringify(moduleName)}: typeof module${index};`)
    .join("\n");

  return `// Generated by flarex-dev. Do not edit.
import { createApi, type ApiFromModules } from "flarex/server";
${imports}

export const api = createApi(${JSON.stringify(metadataByPath, null, 2)}) as unknown as ApiFromModules<{
${moduleTypes}
}>;
`;
}

