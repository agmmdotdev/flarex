import { Effect, Result, Schema } from "effect";
import { BigNumber } from "@medusajs/utils/totals/big-number";
import { BigNumber as NativeBigNumber, MathBN } from "@medusajs/framework/utils/portable";
import { commerceError, isJsonObject, type Json, type JsonObject } from "@flarex/persistence-postgres/internal/commerce-values";
import { commerceDecoder } from "./decoder";
import { captureCommerceInput } from "./input";
import { captureNativeRecord } from "./native-record";

const Numeric = Schema.Union([Schema.String, Schema.Number]);
const Raw = Schema.Struct({
  value: Schema.String,
  precision: Schema.Number.check(Schema.isInt(), Schema.isBetween({ minimum: 1, maximum: 100 })),
}).annotate({ parseOptions: { onExcessProperty: "ignore" } });
const decodeInput = commerceDecoder(Numeric, "invalidInput");
const decodeStored = commerceDecoder(Numeric, "storedCorruption");
const decodeRaw = commerceDecoder(Raw, "storedCorruption");
// Use the executing native arithmetic owner, rather than the ESM constructor
// from another loading path to the same library.
const ArithmeticNumber = MathBN.convert(0).constructor;
export { Raw as ExactNumericRaw };

const nativeNumericInput = (input: unknown, representation: "storage" | "comparison") => Result.try({
  try: () => {
    if (input !== null && typeof input === "object" && input instanceof ArithmeticNumber) return input.toString();
    if (representation === "comparison") return input instanceof NativeBigNumber ? input.bigNumber?.toString() : input;
    if (input instanceof BigNumber) return input.raw?.value;
    return input;
  },
  catch: cause => commerceError("invalidInput", cause),
});

/** Native comparison arguments keep the arithmetic owner's full precision.
 * This finite scalar profile neither rounds through a storage companion nor
 * admits arbitrary objects into the shared JSON boundary. */
export function captureNativeNumericComparisonResult(input: unknown) {
  return Result.gen(function* () {
    const normalized = yield* nativeNumericInput(input, "comparison");
    const value = yield* decodeInput(normalized);
    const numeric = yield* Result.try({ try: () => MathBN.convert(value), catch: cause => commerceError("invalidInput", cause) });
    if (!numeric.isFinite()) return yield* Result.fail(commerceError("invalidInput"));
    return numeric.toString();
  });
}

/** Native precision semantics, with no number round trip before storage. Raw
 * companions are generated by this owner, never accepted as caller write data. */
export const encodeExactNumeric = Effect.fn("MedusaAdapter.encodeExactNumeric")(function* (input: unknown) {
  const normalized = yield* Effect.fromResult(nativeNumericInput(input, "storage"));
  const value = yield* Effect.fromResult(decodeInput(normalized));
  const numeric = yield* Effect.try({ try: () => new BigNumber(value), catch: cause => commerceError("invalidInput", cause) });
  const raw = numeric.raw;
  if (raw === undefined || !Number.isFinite(numeric.numeric) || typeof raw.value !== "string") {
    return yield* Effect.fail(commerceError("invalidInput"));
  }
  return { value: raw.value, raw };
});

/** The native DAL may supply genuine BigNumber objects. Descriptor capture
 * keeps accessors/prototypes inert before converting only declared quantities. */
export const captureExactNumericRow = Effect.fn("MedusaAdapter.captureExactNumericRow")(function* (
  input: unknown, columns: readonly { readonly name: string; readonly defaultValue?: unknown; readonly nullable?: boolean }[], defaults = false,
) {
  const row = yield* captureNativeRecord(input);
  for (const column of columns) {
    if (Object.hasOwn(row, "raw_" + column.name)) return yield* Effect.fail(commerceError("unsupportedProfile"));
    if (row[column.name] === undefined && !defaults) continue;
    if (column.nullable && (row[column.name] === null || row[column.name] === undefined && column.defaultValue == null)) {
      row[column.name] = null; row["raw_" + column.name] = null; continue;
    }
    const encoded = yield* encodeExactNumeric(row[column.name] ?? column.defaultValue);
    row[column.name] = encoded.value; row["raw_" + column.name] = encoded.raw;
  }
  return yield* Effect.fromResult(captureCommerceInput(row)).pipe(Effect.flatMap(value =>
    isJsonObject(value) ? Effect.succeed(value) : Effect.fail(commerceError("invalidInput"))));
});

const decodeNativePair = Schema.decodeUnknownEffect(Schema.Struct({ entity: Schema.Unknown, update: Schema.Unknown }), { onExcessProperty: "error" });
export const captureExactNumericUpdatePair = Effect.fn("MedusaAdapter.captureExactNumericUpdatePair")(function* (
  input: unknown, columns: readonly { readonly name: string; readonly defaultValue?: unknown; readonly nullable?: boolean }[],
) {
  const pair = yield* decodeNativePair(yield* captureNativeRecord(input)).pipe(Effect.mapError(cause => commerceError("unsupportedProfile", cause)));
  return { entity: yield* Effect.fromResult(captureCommerceInput(pair.entity)), update: yield* captureExactNumericRow(pair.update, columns) };
});

/** Call for selected numeric columns only. Physical raw nullability never
 * excuses a missing companion for a present numeric value. */
export const decodeExactNumeric = Effect.fn("MedusaAdapter.decodeExactNumeric")(function* (
  value: unknown, rawValue: unknown, nullable = false,
) {
  if (value === null && rawValue === null && nullable) return null;
  const storedValue = yield* Effect.fromResult(decodeStored(value));
  const raw = yield* Effect.fromResult(decodeRaw(rawValue));
  const numeric = yield* Effect.try({ try: () => new BigNumber(raw), catch: cause => commerceError("storedCorruption", cause) });
  const stored = yield* Effect.try({ try: () => new BigNumber(storedValue), catch: cause => commerceError("storedCorruption", cause) });
  if (!Number.isFinite(numeric.numeric) || numeric.bigNumber === undefined || stored.bigNumber === undefined || !numeric.bigNumber.eq(stored.bigNumber)) {
    return yield* Effect.fail(commerceError("storedCorruption"));
  }
  return numeric.numeric;
});

/** Metadata-selected numeric projection. Native entities can retain exact
 * decimals; public DTOs convert only after every stored companion is checked. */
export const projectExactNumericColumns = Effect.fn("MedusaAdapter.projectExactNumericColumns")(function* (
  value: Json,
  columns: readonly { readonly name: string; readonly nullable?: boolean }[], mode: "exact" | "dto" | "reserialize" = "dto",
) {
  const output: JsonObject[] = [];
  for (const stored of Array.isArray(value) ? value : [value]) {
    if (!isJsonObject(stored)) return yield* Effect.fail(commerceError("storedCorruption"));
    let row: Record<string, Json> | undefined;
    for (const column of columns) if (Object.hasOwn(stored, column.name)) {
      const value = stored[column.name], raw = stored["raw_" + column.name];
      const decoded = yield* Effect.gen(function* () {
        // Native Pricing serializes public numeric DTOs more than once. Validate
        // their raw exact value independently and require the same DTO number.
        if (mode === "reserialize" && typeof value === "number") {
          const companion = yield* Effect.fromResult(decodeRaw(raw));
          const numeric = yield* decodeExactNumeric(companion.value, companion);
          if (numeric !== value) return yield* Effect.fail(commerceError("storedCorruption"));
          return numeric;
        }
        return yield* decodeExactNumeric(value, raw, column.nullable);
      });
      const replacement = mode === "exact" ? value! : decoded;
      if (!Object.is(stored[column.name], replacement)) {
        row ??= { ...stored };
        row[column.name] = replacement;
      }
    }
    output.push(row ?? stored);
  }
  return Array.isArray(value) ? output.every((row, index) => row === value[index]) ? value : output : output[0]!;
});
